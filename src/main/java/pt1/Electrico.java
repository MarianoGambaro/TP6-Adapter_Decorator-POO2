public class Electrico {

    public void conectar() {
        System.out.println("Motor Electrico: Conectando");
    }

    public void activar() {
        System.out.println("Motor Electrico: Motor activado");
    }

    public void moverMasRapido() {
        System.out.println("Motor Electrico: Aumentando velocidad");
    }

    public void detener() {
        System.out.println("Motor Electrico: Deteniendo");
    }

    public void desconectar() {
        System.out.println("Motor Electrico: Desconectado");
    }
}
